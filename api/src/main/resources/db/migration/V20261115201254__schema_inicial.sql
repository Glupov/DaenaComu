-- =============================================================================
-- ENUMS
-- =============================================================================

CREATE TYPE modalidade_curso AS ENUM ('ONLINE', 'PRESENCIAL', 'HIBRIDO');
CREATE TYPE status_inscricao_curso AS ENUM ('RASCUNHO', 'EM_BREVE', 'ABERTA', 'ENCERRADA', 'ARQUIVADO');



-- =============================================================================
-- GEOLOCALIZAÇÃO & ENDEREÇOS
-- =============================================================================

CREATE TABLE paises
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome          TEXT        NOT NULL,
    codigo_alpha2 VARCHAR(2)  NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em   TIMESTAMPTZ,
    CONSTRAINT pk_pais PRIMARY KEY (id),
    CONSTRAINT uq_nome_pais UNIQUE (nome),
    CONSTRAINT uq_codigo_pais UNIQUE (codigo_alpha2)
);
CREATE TABLE estados
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    pais_id     INTEGER     NOT NULL,
    nome        TEXT        NOT NULL,
    sigla       VARCHAR(2),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,
    CONSTRAINT pk_estados PRIMARY KEY (id),
    CONSTRAINT fk_pais_estado FOREIGN KEY (pais_id) REFERENCES paises (id)
);

CREATE TABLE cidades
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estado_id   INTEGER     NOT NULL,
    nome        TEXT        NOT NULL,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,
    CONSTRAINT pk_cidade PRIMARY KEY (id),
    CONSTRAINT fk_estado_cidade FOREIGN KEY (estado_id) REFERENCES estados (id)
);
CREATE TABLE enderecos
(
    id          UUID                 DEFAULT uuidv7(),
    cidade_id   INTEGER     NOT NULL,
    codigo_cep  VARCHAR(20),
    rua         TEXT        NOT NULL,
    numero      VARCHAR(50),
    bairro      TEXT,
    complemento TEXT,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,
    CONSTRAINT pk_endereco PRIMARY KEY (id),
    CONSTRAINT fk_cidade_endereco FOREIGN KEY (cidade_id) REFERENCES cidades (id)
);

CREATE INDEX idx_addresses_city_id ON enderecos (cidade_id);

-- =============================================================================
-- INSTITUIÇÕES & UNIDADES
-- =============================================================================

CREATE TABLE instituicoes
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(255) NOT NULL,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,
    CONSTRAINT pk_instituicao PRIMARY KEY (id)
);

CREATE TABLE unidades
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    instituicao_id INTEGER      NOT NULL,
    endereco_id    UUID         NOT NULL,
    nome           VARCHAR(255) NOT NULL,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    alterado_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    deletado_em    TIMESTAMPTZ,
    CONSTRAINT pk_unidade PRIMARY KEY (id),
    CONSTRAINT fk_instituicao_unidade FOREIGN KEY (instituicao_id) REFERENCES instituicoes (id),
    CONSTRAINT fk_endereco_unidade FOREIGN KEY (endereco_id) REFERENCES enderecos (id)
);

CREATE INDEX idx_unidades_instituicao_id ON unidades (instituicao_id);

-- =============================================================================
-- CORE & DOMAINS
-- =============================================================================

CREATE TABLE cursos
(
    id                    UUID                   DEFAULT uuidv7(),
    instituicao_id        INTEGER                NOT NULL,
    unidade_id            INTEGER,
    nome                  TEXT                   NOT NULL,
    descricao             TEXT                   NOT NULL,
    requisitos            TEXT,
    modalidade            modalidade_curso       NOT NULL DEFAULT 'ONLINE',
    carga_horaria_minutos INTEGER                NOT NULL,
    status_inscricao      status_inscricao_curso NOT NULL DEFAULT 'RASCUNHO',
    mostruario_gratis     BOOLEAN                NOT NULL DEFAULT FALSE,
    url_inscricao         TEXT,
    data_publicacao       TIMESTAMPTZ,
    criado_em             TIMESTAMPTZ            NOT NULL DEFAULT NOW(),
    alterado_em           TIMESTAMPTZ            NOT NULL DEFAULT NOW(),
    deletado_em           TIMESTAMPTZ,

    CONSTRAINT pk_curso PRIMARY KEY (id),
    CONSTRAINT fk_instituicao_curso FOREIGN KEY (instituicao_id) REFERENCES instituicoes (id),
    CONSTRAINT fk_unidade_curso FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT chk_carga_horaria_positiva CHECK (carga_horaria_minutos > 0),

    CONSTRAINT chk_unidade_por_modalidade CHECK (
        (modalidade = 'ONLINE' AND unidade_id IS NULL) OR
        (modalidade IN ('PRESENCIAL', 'HIBRIDO') AND unidade_id IS NOT NULL)
        )
);

CREATE INDEX idx_cursos_instituicao_id ON cursos (instituicao_id);
CREATE INDEX idx_cursos_unidade_id ON cursos (unidade_id) WHERE unidade_id IS NOT NULL;


-- =============================================================================
-- USUÁRIOS, PERFIL & CERTIFICADOS
-- =============================================================================

CREATE TABLE usuarios
(
    id              UUID        DEFAULT uuidv7(),
    endereco_id     UUID,
    nome            TEXT        NOT NULL,
    nome_social     TEXT,
    pronomes        VARCHAR(50),
    email           TEXT        NOT NULL,
    senha_hash      TEXT        NOT NULL,
    data_nascimento DATE,
    bio             TEXT,
    foto_url        TEXT,
    capa_url        TEXT,
    criado_em       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em     TIMESTAMPTZ,

    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT fk_endereco_usuario FOREIGN KEY (endereco_id) REFERENCES enderecos (id)
);

CREATE TABLE certificados
(
    id               UUID        DEFAULT uuidv7(),
    usuario_id       UUID        NOT NULL,
    titulo           TEXT        NOT NULL,
    organizacao      TEXT        NOT NULL,
    data_emissao     DATE        NOT NULL,
    data_expiracao   DATE,
    codigo_credencial TEXT,
    url_credencial   TEXT,
    criado_em        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em      TIMESTAMPTZ,

    CONSTRAINT pk_certificado PRIMARY KEY (id),
    CONSTRAINT fk_usuario_certificado FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_certificados_usuario_id ON certificados (usuario_id);

-- =============================================================================
-- ÁREAS & CARREIRAS
-- =============================================================================

CREATE TABLE areas
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome        TEXT        NOT NULL,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,

    CONSTRAINT pk_area PRIMARY KEY (id),
    CONSTRAINT uq_area_nome UNIQUE (nome)
);

CREATE TABLE carreiras
(
    id                     UUID        DEFAULT uuidv7(),
    nome                   TEXT        NOT NULL,
    descricao              TEXT        NOT NULL,
    principais_habilidades TEXT,
    faixa_salarial_min     NUMERIC(10, 2),
    faixa_salarial_max     NUMERIC(10, 2),
    criado_em              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em            TIMESTAMPTZ,

    CONSTRAINT pk_carreira PRIMARY KEY (id)
);

-- Tabelas Associativas (N:N)
CREATE TABLE areas_cursos
(
    curso_id UUID    NOT NULL,
    area_id  INTEGER NOT NULL,

    CONSTRAINT pk_areas_cursos PRIMARY KEY (curso_id, area_id),
    CONSTRAINT fk_ac_curso FOREIGN KEY (curso_id) REFERENCES cursos (id) ON DELETE CASCADE,
    CONSTRAINT fk_ac_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE CASCADE
);

CREATE TABLE areas_carreiras
(
    carreira_id UUID    NOT NULL,
    area_id     INTEGER NOT NULL,

    CONSTRAINT pk_areas_carreiras PRIMARY KEY (carreira_id, area_id),
    CONSTRAINT fk_acar_carreira FOREIGN KEY (carreira_id) REFERENCES carreiras (id) ON DELETE CASCADE,
    CONSTRAINT fk_acar_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE CASCADE
);

CREATE TABLE cursos_carreiras
(
    curso_id    UUID NOT NULL,
    carreira_id UUID NOT NULL,

    CONSTRAINT pk_cursos_carreiras PRIMARY KEY (curso_id, carreira_id),
    CONSTRAINT fk_cc_curso FOREIGN KEY (curso_id) REFERENCES cursos (id) ON DELETE CASCADE,
    CONSTRAINT fk_cc_carreira FOREIGN KEY (carreira_id) REFERENCES carreiras (id) ON DELETE CASCADE
);

-- =============================================================================
-- CONTEÚDOS & AVALIAÇÕES DE CURSOS
-- =============================================================================

CREATE TABLE conteudos
(
    id               UUID        DEFAULT uuidv7(),
    curso_id         UUID        NOT NULL,
    nome             TEXT        NOT NULL,
    material         TEXT,
    duracao_minutos  INTEGER,
    data_publicacao  TIMESTAMPTZ,
    criado_em        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em      TIMESTAMPTZ,

    CONSTRAINT pk_conteudo PRIMARY KEY (id),
    CONSTRAINT fk_curso_conteudo FOREIGN KEY (curso_id) REFERENCES cursos (id) ON DELETE CASCADE,
    CONSTRAINT chk_conteudo_duracao_positiva CHECK (duracao_minutos IS NULL OR duracao_minutos > 0)
);

CREATE INDEX idx_conteudos_curso_id ON conteudos (curso_id);

CREATE TABLE avaliacoes
(
    id          UUID        DEFAULT uuidv7(),
    curso_id    UUID        NOT NULL,
    usuario_id  UUID        NOT NULL,
    pontos      SMALLINT    NOT NULL,
    comentario  TEXT,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,

    CONSTRAINT pk_avaliacao PRIMARY KEY (id),
    CONSTRAINT fk_curso_avaliacao FOREIGN KEY (curso_id) REFERENCES cursos (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_avaliacao FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT chk_pontos_intervalo CHECK (pontos BETWEEN 1 AND 5),
    CONSTRAINT uq_avaliacao_usuario_curso UNIQUE (curso_id, usuario_id)
);

CREATE INDEX idx_avaliacoes_curso_id ON avaliacoes (curso_id);

-- =============================================================================
-- COMUNIDADE (POSTS, COMENTÁRIOS & CURTIDAS)
-- =============================================================================

CREATE TABLE posts
(
    id            UUID        DEFAULT uuidv7(),
    usuario_id    UUID        NOT NULL,
    curso_id      UUID,
    conteudo      TEXT        NOT NULL,
    categoria     VARCHAR(100),
    imagem_url    TEXT,
    visualizacoes INTEGER     NOT NULL DEFAULT 0,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em   TIMESTAMPTZ,

    CONSTRAINT pk_post PRIMARY KEY (id),
    CONSTRAINT fk_usuario_post FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_curso_post FOREIGN KEY (curso_id) REFERENCES cursos (id) ON DELETE SET NULL
);

CREATE INDEX idx_posts_usuario_id ON posts (usuario_id);
CREATE INDEX idx_posts_curso_id ON posts (curso_id);

CREATE TABLE post_comentarios
(
    id          UUID        DEFAULT uuidv7(),
    post_id     UUID        NOT NULL,
    usuario_id  UUID        NOT NULL,
    texto       TEXT        NOT NULL,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletado_em TIMESTAMPTZ,

    CONSTRAINT pk_post_comentario PRIMARY KEY (id),
    CONSTRAINT fk_post_comentario FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_comentario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_post_comentarios_post_id ON post_comentarios (post_id);

CREATE TABLE post_curtidas
(
    post_id    UUID        NOT NULL,
    usuario_id UUID        NOT NULL,
    criado_em  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_post_curtida PRIMARY KEY (post_id, usuario_id),
    CONSTRAINT fk_post_curtida FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_curtida FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
